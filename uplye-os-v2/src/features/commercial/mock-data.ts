type LightClient = Pick<Client, 'id' | 'name' | 'initials' | 'contactName' | 'city' | 'sector' | 'status' | 'revenue12m' | 'revenueNote' | 'lastExchange'> & {
  email: string
  role?: string
}

/** Fiches plus légères : les sections vides affichent un état vide plutôt que des données inventées. */
function lightClient({ email, role = 'Contact principal', ...c }: LightClient): Client {
  const initials = c.contactName
    .split(' ')
    .map((p) => p[0])
    .join('')
    .slice(0, 2)
    .toUpperCase()
  return {
    ...c,
    summary: `${c.contactName}. ${c.city}.`,
    contacts: [{ id: `${c.id}-c1`, name: c.contactName, initials, role, email, phone: '+33600000000', primary: true }],
    pinned: [],
    projects: [],
    invoices: [],
    files: [],
    activity: [{ id: `${c.id}-a1`, kind: 'note', title: c.lastExchange.label, detail: c.revenueNote, date: c.lastExchange.date, category: 'echange' }],
  }
}

